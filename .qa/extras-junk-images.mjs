// Pictures cut out of the edition PDFs include, besides the printed
// photographs, the pieces a page is *made* of: a slice of the sky behind an
// advertisement, a flat panel of the page's background colour, the black and
// white alpha mask that cut a model out, the soft grey blob behind a product.
// Set beside real photographs they read as a scattered puzzle, so they are
// listed here and left out of the page.
//
// Three measures, all on a 96x96 sample of the file flattened onto white:
//   grad  average difference between neighbouring pixels — a flat panel or a
//         gradient has almost none, a photograph has plenty
//   sd    spread of tone — a near-solid fragment has little
//   mid   share of pixels that are neither near-black nor near-white, with
//         sat (average colour) — a two-tone, colourless image is a mask
//
// Usage (from .qa/): node extras-junk-images.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const sharp = require("../node_modules/sharp");

const root = path.resolve("..");
const src = fs.readFileSync(path.join(root, "src/data/extras.ts"), "utf8");
const extras = JSON.parse(src.slice(src.indexOf("= {") + 2, src.lastIndexOf("};") + 1));

const seen = new Map();
for (const block of Object.values(extras).flat()) for (const img of block.images) seen.set(img.src, img);

async function measure(file) {
  const W = 96;
  const { data } = await sharp(file).flatten({ background: "#ffffff" }).resize(W, W, { fit: "fill" }).raw().toBuffer({ resolveWithObject: true });
  const grey = new Uint8Array(W * W);
  let sat = 0;
  let mid = 0;
  for (let i = 0; i < W * W; i++) {
    const r = data[i * 3], g = data[i * 3 + 1], b = data[i * 3 + 2];
    sat += Math.max(r, g, b) - Math.min(r, g, b);
    const v = (r * 0.299 + g * 0.587 + b * 0.114) | 0;
    grey[i] = v;
    if (v > 40 && v < 215) mid++;
  }
  let sum = 0, sum2 = 0, grad = 0, pairs = 0;
  for (let y = 0; y < W; y++)
    for (let x = 0; x < W; x++) {
      const v = grey[y * W + x];
      sum += v;
      sum2 += v * v;
      if (x + 1 < W) { grad += Math.abs(v - grey[y * W + x + 1]); pairs++; }
      if (y + 1 < W) { grad += Math.abs(v - grey[(y + 1) * W + x]); pairs++; }
    }
  const n = W * W;
  const mean = sum / n;
  return { sd: Math.sqrt(sum2 / n - mean * mean), grad: grad / pairs, sat: sat / n, mid: mid / n };
}

/** Flat panel or gradient; near-solid; or a colourless two-tone mask. */
const isJunk = (m) => m.grad < 2 || m.sd < 16 || (m.mid < 0.25 && m.sat < 18 && m.grad < 8);

const junk = [];
for (const [src, meta] of seen) {
  const file = path.join(root, "public", src);
  if (!fs.existsSync(file)) continue;
  // a fragment too small to print at a usable size is a leftover too
  if (Math.min(meta.width, meta.height) < 120) { junk.push(src); continue; }
  if (isJunk(await measure(file))) junk.push(src);
}

junk.sort();
const out = `import type { StoryExtra } from "@/types";

/**
 * Pictures cut out of the edition PDFs that are not pictures: flat panels of a
 * page's background, slices of sky behind an advertisement, the black-and-white
 * masks that cut a model out, the soft blob of a drop shadow. They are left out
 * of the printed pages shown on the web, where they read as scattered debris.
 *
 * Generated by .qa/extras-junk-images.mjs — do not edit by hand.
 */
const junk = new Set<string>([
${junk.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
]);

/** True when a picture is page furniture rather than a photograph. */
export const isJunkExtraImage = (img: StoryExtra["images"][number]) => junk.has(img.src);
`;
fs.writeFileSync(path.join(root, "src/data/extrasJunkImages.ts"), out);
console.log(`pictures ${seen.size}, left out ${junk.length}, kept ${seen.size - junk.length}`);
